      _model.pagetimers?.cancel();
      if (FFAppState().txStatus == 'complete') {
        _model.remainingMins = 0;
        _model.progress01 = 1.0;
        safeSetState(() {});
      } else {
        _model.elapsedMins = functions.incElapsedFromStart(
